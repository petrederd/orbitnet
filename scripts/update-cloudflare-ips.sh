#!/usr/bin/env bash
# Regenerates cloudflare-ips.conf and the Caddy trusted_proxies fragment from
# Cloudflare's published ranges. Both files are committed so local builds work
# offline; the deploy workflow runs this after the pull and before rebuilding
# so the ranges never go stale.
#
# The generated Caddy fragment is written in place when it is already mounted,
# which preserves the inode of a single-file bind mount. A container must mount
# the fragment file or its config directory from the host; an ephemeral
# docker-cp copy is refused because it disappears when the container is
# recreated. Caddy is reloaded only when the fragment actually changes.
#
# Optional environment:
#   CADDY_CONTAINER     container name (auto-detected when unset)
#   CADDY_CONFIG_PATH   Caddyfile path inside the container (/etc/caddy/Caddyfile)
#   CADDY_CONFIG_DIR    host config directory for a non-Docker Caddy
#   CADDY_RELOAD_CMD    reload command for a non-Docker Caddy
#   CADDY_SKIP_RELOAD=1 update repository files only
set -euo pipefail

cd "$(dirname "$0")/.."
out="cloudflare-ips.conf"
caddy_out="deploy/cloudflare-trusted-proxies.caddy"
tmp="$(mktemp)"
tmp_caddy="$(mktemp)"
trap 'rm -f "$tmp" "$tmp_caddy"' EXIT

fetched=1
if ! v4="$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v4)" ||
   ! v6="$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v6)"; then
  fetched=0
fi
if [ "$fetched" = 1 ] && { [ -z "$v4" ] || [ -z "$v6" ]; }; then
  fetched=0
fi

if [ "$fetched" = 0 ]; then
  echo "warning: could not fetch Cloudflare ranges; keeping the committed files" >&2
else
  {
    echo "# Cloudflare edge ranges — do not edit by hand."
    echo "#"
    echo "# Generated by scripts/update-cloudflare-ips.sh from:"
    echo "#   https://www.cloudflare.com/ips-v4"
    echo "#   https://www.cloudflare.com/ips-v6"
    echo
    echo "# Cloudflare IPv4"
    while IFS= read -r ip; do
      [ -n "$ip" ] && echo "set_real_ip_from $ip;"
    done <<< "$v4"
    echo
    echo "# Cloudflare IPv6"
    while IFS= read -r ip; do
      [ -n "$ip" ] && echo "set_real_ip_from $ip;"
    done <<< "$v6"
  } > "$tmp"

  if cmp -s "$tmp" "$out"; then
    echo "$out is already current"
  else
    mv "$tmp" "$out"
    chmod 644 "$out"
    echo "updated $out"
  fi

  # Caddy consumes the same list as a trusted_proxies fragment. Keeping it
  # generated avoids the two files drifting apart.
  mapfile -t ranges < <(printf '%s\n%s\n' "$v4" "$v6" | sed '/^$/d')
  {
    echo "# Cloudflare edge ranges for Caddy trusted_proxies — do not edit by hand."
    echo "#"
    echo "# Generated by scripts/update-cloudflare-ips.sh from:"
    echo "#   https://www.cloudflare.com/ips-v4"
    echo "#   https://www.cloudflare.com/ips-v6"
    echo
    echo "trusted_proxies static \\"
    last=$((${#ranges[@]} - 1))
    for i in "${!ranges[@]}"; do
      if [ "$i" -eq "$last" ]; then
        echo "  ${ranges[$i]}"
      else
        echo "  ${ranges[$i]} \\"
      fi
    done
  } > "$tmp_caddy"

  if cmp -s "$tmp_caddy" "$caddy_out"; then
    echo "$caddy_out is already current"
  else
    mv "$tmp_caddy" "$caddy_out"
    chmod 644 "$caddy_out"
    echo "updated $caddy_out"
  fi
fi

if [ "${CADDY_SKIP_RELOAD:-0}" = "1" ]; then
  echo "Caddy publish and reload skipped (CADDY_SKIP_RELOAD=1)"
  exit 0
fi

caddy_fragment="cloudflare-trusted-proxies.caddy"
caddy_config_path="${CADDY_CONFIG_PATH:-/etc/caddy/Caddyfile}"
caddy_container="${CADDY_CONTAINER:-}"
caddy_config_dir="${CADDY_CONFIG_DIR:-}"
host_sha="$(sha256sum "$caddy_out" | cut -d' ' -f1)"
caddy_changed=0

sync_fragment() {
  local dest="$1"
  local current=""
  if [ -f "$dest" ]; then
    current="$(sha256sum "$dest" | cut -d' ' -f1)"
  fi
  if [ "$current" = "$host_sha" ]; then
    echo "Caddy fragment is already current: $dest"
    return 0
  fi
  if [ -e "$dest" ]; then
    # Truncate in place so a single-file bind mount keeps pointing at this inode.
    if ! cat "$caddy_out" > "$dest"; then
      echo "error: cannot write $dest" >&2
      return 1
    fi
  else
    if ! install -m 0644 "$caddy_out" "$dest"; then
      echo "error: cannot create $dest" >&2
      return 1
    fi
  fi
  chmod 0644 "$dest" 2>/dev/null || true
  caddy_changed=1
  echo "updated $dest"
}

if [ -z "$caddy_container" ] && command -v docker >/dev/null 2>&1; then
  caddy_container="$(docker ps --format '{{.Names}}' 2>/dev/null | grep -E '(^|[-_])caddy([-_.]|$)' | head -n 1 || true)"
fi

if [ -n "$caddy_container" ]; then
  if ! command -v docker >/dev/null 2>&1; then
    echo "error: CADDY_CONTAINER is set but docker is not available" >&2
    exit 1
  fi
  if ! docker exec "$caddy_container" test -r "$caddy_config_path"; then
    echo "error: cannot read $caddy_config_path in $caddy_container" >&2
    exit 1
  fi
  if ! docker exec "$caddy_container" grep -q 'cloudflare-trusted-proxies.caddy' "$caddy_config_path"; then
    echo "warning: $caddy_config_path does not import $caddy_fragment; skipping Caddy publish and reload" >&2
    exit 0
  fi

  container_config_dir="$(dirname "$caddy_config_path")"
  container_fragment="$container_config_dir/$caddy_fragment"
  fragment_source="$(docker inspect --format '{{range .Mounts}}{{if eq .Destination "'"$container_fragment"'"}}{{.Source}}{{end}}{{end}}' "$caddy_container")"
  config_source=""
  if [ -z "$fragment_source" ]; then
    config_source="$(docker inspect --format '{{range .Mounts}}{{if eq .Destination "'"$container_config_dir"'"}}{{.Source}}{{end}}{{end}}' "$caddy_container")"
  fi

  if [ -n "$fragment_source" ]; then
    dest="$fragment_source"
  elif [ -n "$config_source" ]; then
    dest="$config_source/$caddy_fragment"
  else
    echo "error: $caddy_container imports $caddy_fragment but $container_fragment is not mounted from the host" >&2
    echo "error: mount the fragment file or its config directory; an ephemeral docker cp would be lost on container recreation" >&2
    exit 1
  fi

  sync_fragment "$dest"

  container_sha="$(docker exec "$caddy_container" sha256sum "$container_fragment" | cut -d' ' -f1)"
  if [ "$container_sha" != "$host_sha" ]; then
    echo "error: $caddy_container still sees a different $container_fragment (inode/mount mismatch)" >&2
    echo "error: mount the config directory or update the mounted file in place" >&2
    exit 1
  fi

  if [ "$caddy_changed" = 1 ]; then
    docker exec "$caddy_container" caddy reload --config "$caddy_config_path"
    echo "reloaded Caddy in $caddy_container"
  else
    echo "Caddy reload skipped: $caddy_fragment is unchanged"
  fi
elif [ -n "$caddy_config_dir" ]; then
  dest="$caddy_config_dir/$caddy_fragment"
  sync_fragment "$dest"
  if [ "$caddy_changed" = 1 ]; then
    if [ -n "${CADDY_RELOAD_CMD:-}" ]; then
      sh -c "$CADDY_RELOAD_CMD"
      echo "reloaded Caddy with CADDY_RELOAD_CMD"
    else
      echo "warning: updated $dest but CADDY_RELOAD_CMD is not set; Caddy still uses the old ranges" >&2
    fi
  else
    echo "Caddy reload skipped: $caddy_fragment is unchanged"
  fi
else
  echo "warning: Caddy not detected; updated repository files only" >&2
  echo "warning: set CADDY_CONTAINER or CADDY_CONFIG_DIR to install and reload the fragment" >&2
fi
