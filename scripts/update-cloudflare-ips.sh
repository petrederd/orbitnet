#!/usr/bin/env bash
# Regenerates cloudflare-ips.conf and the Caddy trusted_proxies fragment from
# Cloudflare's published ranges. Both files are committed so local builds work
# offline; the deploy workflow runs this before rebuilding so the ranges never
# go stale.
set -euo pipefail

cd "$(dirname "$0")/.."
out="cloudflare-ips.conf"
caddy_out="deploy/cloudflare-trusted-proxies.caddy"
tmp="$(mktemp)"
tmp_caddy="$(mktemp)"
trap 'rm -f "$tmp" "$tmp_caddy"' EXIT

v4="$(curl -fsS https://www.cloudflare.com/ips-v4)"
v6="$(curl -fsS https://www.cloudflare.com/ips-v6)"

{
  echo "# Cloudflare edge ranges — do not edit by hand."
  echo "#"
  echo "# Generated by scripts/update-cloudflare-ips.sh from:"
  echo "#   https://www.cloudflare.com/ips-v4"
  echo "#   https://www.cloudflare.com/ips-v6"
  echo
  echo "# Cloudflare IPv4"
  while IFS= read -r ip; do
    [ -n "$ip" ] && echo "set_real_ip_from $ip;"
  done <<< "$v4"
  echo
  echo "# Cloudflare IPv6"
  while IFS= read -r ip; do
    [ -n "$ip" ] && echo "set_real_ip_from $ip;"
  done <<< "$v6"
} > "$tmp"

mv "$tmp" "$out"
chmod 644 "$out"
echo "updated $out"

# Caddy consumes the same list as a trusted_proxies fragment. Keeping it
# generated avoids the two files drifting apart.
mapfile -t ranges < <(printf '%s\n%s\n' "$v4" "$v6" | sed '/^$/d')
{
  echo "# Cloudflare edge ranges for Caddy trusted_proxies — do not edit by hand."
  echo "#"
  echo "# Generated by scripts/update-cloudflare-ips.sh from:"
  echo "#   https://www.cloudflare.com/ips-v4"
  echo "#   https://www.cloudflare.com/ips-v6"
  echo
  echo "trusted_proxies static \\"
  last=$((${#ranges[@]} - 1))
  for i in "${!ranges[@]}"; do
    if [ "$i" -eq "$last" ]; then
      echo "  ${ranges[$i]}"
    else
      echo "  ${ranges[$i]} \\"
    fi
  done
} > "$tmp_caddy"

mv "$tmp_caddy" "$caddy_out"
chmod 644 "$caddy_out"
echo "updated $caddy_out"